-- Migração inicial. Execute uma única vez em um banco vazio.
CREATE SCHEMA dieta_facil;
SET search_path TO dieta_facil, pg_catalog;

CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL CHECK (length(trim(nome)) > 0),
    nome_usuario TEXT NOT NULL,
    email TEXT NOT NULL,
    senha_hash TEXT NOT NULL,
    email_verificado_em TIMESTAMPTZ
);

CREATE TABLE comum (
    usuario_id BIGINT PRIMARY KEY REFERENCES usuario(id) ON DELETE CASCADE ON UPDATE RESTRICT
);

CREATE TABLE nutricionista (
    usuario_id BIGINT PRIMARY KEY REFERENCES usuario(id) ON DELETE CASCADE ON UPDATE RESTRICT,
    crn TEXT NOT NULL UNIQUE,
    descricao TEXT,
    endereco_trabalho TEXT NOT NULL CHECK (length(trim(endereco_trabalho)) > 0)
);

CREATE TABLE meta (
    comum_id BIGINT PRIMARY KEY REFERENCES comum(usuario_id) ON DELETE CASCADE ON UPDATE RESTRICT,
    calorias_diarias NUMERIC NOT NULL CHECK (calorias_diarias > 0 AND calorias_diarias < 'Infinity'::numeric),
    sexo TEXT,
    data_nascimento DATE,
    altura_cm NUMERIC CHECK (altura_cm > 0 AND altura_cm < 'Infinity'::numeric),
    peso_atual_kg NUMERIC CHECK (peso_atual_kg > 0 AND peso_atual_kg < 'Infinity'::numeric),
    peso_meta_kg NUMERIC CHECK (peso_meta_kg > 0 AND peso_meta_kg < 'Infinity'::numeric),
    nivel_atividade TEXT
);

CREATE TABLE cardapio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comum_id BIGINT NOT NULL REFERENCES comum(usuario_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    nome TEXT NOT NULL,
    categoria TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE refeicao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cardapio_id BIGINT REFERENCES cardapio(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    nome TEXT NOT NULL
);

CREATE TABLE registro (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comum_id BIGINT NOT NULL REFERENCES comum(usuario_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    refeicao_id BIGINT NOT NULL UNIQUE REFERENCES refeicao(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    registrado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE alimento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comum_id BIGINT REFERENCES comum(usuario_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    nome TEXT NOT NULL,
    unidade_base TEXT NOT NULL CHECK (unidade_base IN ('g', 'ml')),
    kcal_por_100 NUMERIC NOT NULL CHECK (kcal_por_100 >= 0 AND kcal_por_100 < 'Infinity'::numeric),
    proteinas_g_por_100 NUMERIC NOT NULL CHECK (proteinas_g_por_100 >= 0 AND proteinas_g_por_100 < 'Infinity'::numeric),
    carboidratos_g_por_100 NUMERIC NOT NULL CHECK (carboidratos_g_por_100 >= 0 AND carboidratos_g_por_100 < 'Infinity'::numeric),
    gorduras_g_por_100 NUMERIC NOT NULL CHECK (gorduras_g_por_100 >= 0 AND gorduras_g_por_100 < 'Infinity'::numeric)
);

CREATE TABLE alimento_consumido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refeicao_id BIGINT NOT NULL REFERENCES refeicao(id) ON DELETE CASCADE ON UPDATE RESTRICT,
    alimento_id BIGINT NOT NULL REFERENCES alimento(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    quantidade NUMERIC NOT NULL CHECK (quantidade > 0 AND quantidade < 'Infinity'::numeric)
);

CREATE TABLE vinculo_paciente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comum_id BIGINT NOT NULL REFERENCES comum(usuario_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    nutricionista_id BIGINT NOT NULL REFERENCES nutricionista(usuario_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    encerrado_em TIMESTAMPTZ,
    UNIQUE (comum_id, nutricionista_id),
    UNIQUE (id, comum_id, nutricionista_id)
);

CREATE TABLE mensagem (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vinculo_id BIGINT NOT NULL,
    comum_id BIGINT NOT NULL REFERENCES comum(usuario_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    nutricionista_id BIGINT NOT NULL REFERENCES nutricionista(usuario_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    origem TEXT NOT NULL CHECK (origem IN ('comum', 'nutricionista')),
    corpo TEXT NOT NULL CHECK (length(trim(corpo)) > 0),
    enviada_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (vinculo_id, comum_id, nutricionista_id)
        REFERENCES vinculo_paciente(id, comum_id, nutricionista_id) ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE TABLE avaliacao (
    vinculo_id BIGINT PRIMARY KEY REFERENCES vinculo_paciente(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    nota INTEGER NOT NULL CHECK (nota BETWEEN 1 AND 5),
    comentario TEXT,
    criada_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE resultado_bioimpedancia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vinculo_id BIGINT NOT NULL REFERENCES vinculo_paciente(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    medido_em TIMESTAMPTZ NOT NULL,
    peso_kg NUMERIC NOT NULL CHECK (peso_kg > 0 AND peso_kg < 'Infinity'::numeric),
    gordura_percentual NUMERIC CHECK (gordura_percentual BETWEEN 0 AND 100)
);

CREATE TABLE agenda (
    nutricionista_id BIGINT PRIMARY KEY REFERENCES nutricionista(usuario_id) ON DELETE CASCADE ON UPDATE RESTRICT
);

CREATE TABLE consulta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nutricionista_id BIGINT NOT NULL REFERENCES agenda(nutricionista_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    paciente_id BIGINT NOT NULL,
    inicio_em TIMESTAMPTZ NOT NULL,
    fim_em TIMESTAMPTZ NOT NULL CHECK (fim_em > inicio_em),
    status TEXT NOT NULL DEFAULT 'agendada'
        CHECK (status IN ('agendada', 'realizada', 'cancelada')),
    FOREIGN KEY (paciente_id, nutricionista_id)
        REFERENCES vinculo_paciente(comum_id, nutricionista_id) ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE INDEX idx_item_refeicao ON alimento_consumido(refeicao_id);
CREATE UNIQUE INDEX uq_usuario_nome_usuario ON usuario(lower(nome_usuario));
CREATE UNIQUE INDEX uq_usuario_email ON usuario(lower(email));
CREATE INDEX idx_alimento_nome ON alimento(lower(nome));
CREATE INDEX idx_registro_comum_data ON registro(comum_id, registrado_em);
CREATE INDEX idx_mensagem_vinculo_data ON mensagem(vinculo_id, enviada_em);

CREATE INDEX idx_mensagem_comum_data ON mensagem(comum_id, enviada_em);
CREATE INDEX idx_mensagem_nutricionista_data ON mensagem(nutricionista_id, enviada_em);
